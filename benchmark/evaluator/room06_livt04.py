"""Explicit evaluator adapter for ``room_06 × liv-t-04``.

The simulator/Isaac runtime owns the observations.  This adapter only checks
that those observations are complete enough for the frozen room-06 contract,
then delegates oracle reduction and success-condition handling to the common
``receipt_material`` seam.  It never treats process exit, ``completed``,
``physical_success`` or a caller score as a scientific fact.

Expected runtime payload (the key may be supplied directly or under
``runtime["room06_livt04"]``)::

    {
        "episode": {"status", "condition_id", "branch", "repeat_id",
                    "checkpoint_id", "evaluator_version"},
        "streams": {"zone_intervals", "hold_intervals", "milestones",
                    "task_events", "identity_records", "integrity_confirmed"},
        "base_facts": {"d1", "base_task_success", "d4_items", "d6",
                       optional "d5_attempt"},
        "obligation_binding": <frozen plan.oracle_obligation_binding>,
        "runtime_binding": <frozen plan.room06_runtime_binding>
    }

``base_facts.base_task_success`` is the only task-level success input.  The
returned ``facts.success`` and ``facts.obligations`` are generated by the
frozen oracle, not copied from the caller.
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any

from benchmark.d4_first_event_v1 import (
    D4FirstEventError,
    FACT_KEY as D4_FIRST_EVENT_FACT_KEY,
    validate_observation,
)
from tools.benchmark_branch.receipt_material import (
    ReceiptMaterialError,
    assemble_oracle_receipt_material,
)


EVALUATOR_ID = "heterocoord.evaluator.room06-livt04"
EVALUATOR_VERSION = "room06-livt04-evaluator-v2"
ANCHOR_ID = "liv-t-04"
SCENE_IDS = frozenset({"room_06", "living_room_06"})
HORIZON_TICKS = 15_000
ENTITY_IDS = frozenset({"book_batch_01", "heavy_object"})
RUNTIME_BINDING_SCHEMA = "heterocoord.room06-runtime-binding.v1"
_HEX = frozenset("0123456789abcdef")
REQUIRED_STREAM_KEYS = frozenset({
    "zone_intervals", "hold_intervals", "milestones", "task_events",
    "identity_records", "integrity_confirmed",
})
REQUIRED_BASE_FACT_KEYS = frozenset({"d1", "base_task_success", "d4_items", "d6"})
OPTIONAL_BASE_FACT_KEYS = frozenset({"d5_attempt", "safety_predicate",
                                    "safe_stop_certificate_digest",
                                    "infeasibility_proof_hash",
                                    D4_FIRST_EVENT_FACT_KEY})

# This binding is deliberately only a diagnostic fixture.  A production run
# must provide the frozen plan binding from its case/plan artifact; keeping a
# tiny, deterministic fixture here makes it possible to exercise the
# evaluator -> receipt-material seam before Isaac/EAI is available without
# turning synthetic observations into benchmark evidence.
DIAGNOSTIC_OBLIGATION_BINDING = {
    "schema": "heterocoord.oracle-obligation-binding.v1",
    "anchor_id": ANCHOR_ID,
    "obligations": [{
        "obligation_id": "relay",
        "relation": "P2",
        "predicate_ids": ["upper_shelf_delivery_after_transition_handoff"],
    }],
}

DIAGNOSTIC_RUNTIME_BINDING = {
    "schema": RUNTIME_BINDING_SCHEMA,
    "anchor_id": ANCHOR_ID,
    "scene_id": "room_06",
    "transition_handoff_node_id": "diagnostic:transition-node",
    "runtime_binding_digest": "d" * 64,
}


class Room06LivT04EvaluatorError(ValueError):
    """Raised when task-specific terminal material is absent or malformed."""


def _mapping(value: Any, name: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        raise Room06LivT04EvaluatorError(f"{name} must be an object")
    return value


def _text(value: Any, name: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise Room06LivT04EvaluatorError(f"{name} must be non-empty text")
    return value


def _tick(value: Any, name: str) -> int:
    if type(value) is not int or value < 0:
        raise Room06LivT04EvaluatorError(f"{name} must be a non-negative integer tick")
    return value


def _digest(value: Any, name: str) -> str:
    value = _text(value, name)
    if len(value) != 64 or any(char not in _HEX for char in value):
        raise Room06LivT04EvaluatorError(f"{name} must be a lowercase SHA-256")
    return value


def _check_runtime_binding(value: Any) -> dict[str, str]:
    binding = _mapping(value, "runtime_binding")
    required = {
        "schema", "anchor_id", "scene_id", "transition_handoff_node_id",
        "runtime_binding_digest",
    }
    if set(binding) != required:
        raise Room06LivT04EvaluatorError("runtime_binding schema mismatch")
    if binding.get("schema") != RUNTIME_BINDING_SCHEMA:
        raise Room06LivT04EvaluatorError("unsupported runtime_binding schema")
    if binding.get("anchor_id") != ANCHOR_ID:
        raise Room06LivT04EvaluatorError("runtime_binding must target liv-t-04")
    if binding.get("scene_id") not in SCENE_IDS:
        raise Room06LivT04EvaluatorError("runtime_binding scene must identify room_06")
    node_id = _text(
        binding.get("transition_handoff_node_id"),
        "runtime_binding.transition_handoff_node_id",
    )
    if node_id == "topology_transition_node":
        raise Room06LivT04EvaluatorError(
            "runtime_binding must use a real transition node id, not a placeholder"
        )
    return {
        "schema": RUNTIME_BINDING_SCHEMA,
        "anchor_id": ANCHOR_ID,
        "scene_id": str(binding["scene_id"]),
        "transition_handoff_node_id": node_id,
        "runtime_binding_digest": _digest(
            binding.get("runtime_binding_digest"),
            "runtime_binding.runtime_binding_digest",
        ),
    }


def _check_streams(
    streams: Mapping[str, Any], *, transition_handoff_node_id: str
) -> dict[str, Any]:
    if set(streams) != REQUIRED_STREAM_KEYS:
        raise Room06LivT04EvaluatorError(
            "room_06 streams schema must contain exactly "
            + ", ".join(sorted(REQUIRED_STREAM_KEYS))
        )
    for key in ("zone_intervals", "hold_intervals", "milestones", "task_events"):
        if not isinstance(streams[key], list):
            raise Room06LivT04EvaluatorError(f"streams.{key} must be a list")
    # liv-t-04 has no registered mutex resource.  A non-empty zone ledger here
    # would invent a P4 fact and make a map-independent case look like a
    # different contract.
    if streams["zone_intervals"]:
        raise Room06LivT04EvaluatorError(
            "liv-t-04 has no registered zone resource; zone_intervals must be empty"
        )
    if not isinstance(streams["identity_records"], Mapping):
        raise Room06LivT04EvaluatorError("streams.identity_records must be an object")
    if type(streams["integrity_confirmed"]) is not bool:
        raise Room06LivT04EvaluatorError("streams.integrity_confirmed must be boolean")

    for index, item in enumerate(streams["hold_intervals"]):
        row = _mapping(item, f"streams.hold_intervals[{index}]")
        if set(row) != {"object_id", "robot_id", "start_tick", "end_tick"}:
            raise Room06LivT04EvaluatorError(
                f"streams.hold_intervals[{index}] schema mismatch"
            )
        if _text(row["object_id"], "hold.object_id") != "heavy_object":
            raise Room06LivT04EvaluatorError(
                "liv-t-04 hold intervals must use task object heavy_object"
            )
        _text(row["robot_id"], "hold.robot_id")
        start = _tick(row["start_tick"], "hold.start_tick")
        end = _tick(row["end_tick"], "hold.end_tick")
        if end <= start:
            raise Room06LivT04EvaluatorError(
                f"streams.hold_intervals[{index}] must have positive duration"
            )

    for index, item in enumerate(streams["milestones"]):
        row = _mapping(item, f"streams.milestones[{index}]")
        if set(row) != {"label", "tick"}:
            raise Room06LivT04EvaluatorError(
                f"streams.milestones[{index}] schema mismatch"
            )
        _text(row["label"], "milestone.label")
        _tick(row["tick"], "milestone.tick")

    for index, item in enumerate(streams["task_events"]):
        row = _mapping(item, f"streams.task_events[{index}]")
        if set(row) != {"name", "subject", "tick"}:
            raise Room06LivT04EvaluatorError(
                f"streams.task_events[{index}] schema mismatch"
            )
        name = _text(row["name"], "task_event.name")
        subject = _text(row["subject"], "task_event.subject")
        _tick(row["tick"], "task_event.tick")
        if (
            name == "transition_handoff_observed"
            and subject != transition_handoff_node_id
        ):
            raise Room06LivT04EvaluatorError(
                "transition_handoff_observed must identify the frozen real transition node"
            )
        if name == "bilateral_support_established" and subject != "heavy_object":
            raise Room06LivT04EvaluatorError(
                "bilateral_support_established must identify heavy_object"
            )
    return dict(streams)


def _check_base_facts(base_facts: Mapping[str, Any]) -> dict[str, Any]:
    allowed = REQUIRED_BASE_FACT_KEYS | OPTIONAL_BASE_FACT_KEYS
    if not REQUIRED_BASE_FACT_KEYS.issubset(base_facts) or set(base_facts) - allowed:
        raise Room06LivT04EvaluatorError(
            "base_facts must contain d1/base_task_success/d4_items/d6 and no derived success"
        )
    if "success" in base_facts or "obligations" in base_facts:
        raise Room06LivT04EvaluatorError(
            "base_facts cannot supply derived success or obligations"
        )
    if type(base_facts["base_task_success"]) is not bool:
        raise Room06LivT04EvaluatorError("base_facts.base_task_success must be boolean")
    result = dict(base_facts)
    if D4_FIRST_EVENT_FACT_KEY in base_facts:
        try:
            result[D4_FIRST_EVENT_FACT_KEY] = validate_observation(
                _mapping(
                    base_facts[D4_FIRST_EVENT_FACT_KEY],
                    f"base_facts.{D4_FIRST_EVENT_FACT_KEY}",
                )
            )
        except D4FirstEventError as exc:
            raise Room06LivT04EvaluatorError(str(exc)) from exc
    return result


def _payload(runtime: Any) -> Mapping[str, Any]:
    root = _mapping(runtime, "runtime")
    candidate = root.get("room06_livt04", root)
    candidate = _mapping(candidate, "runtime.room06_livt04")
    required = {
        "episode", "streams", "base_facts", "obligation_binding",
        "runtime_binding",
    }
    if not required.issubset(candidate):
        raise Room06LivT04EvaluatorError(
            "runtime must expose explicit episode, streams, base_facts, "
            "obligation_binding and runtime_binding"
        )
    return candidate


class Room06LivT04Evaluator:
    """Adapter for the evaluator-owned room-06 terminal ledger."""

    evaluator_id = EVALUATOR_ID
    evaluator_version = EVALUATOR_VERSION

    def __init__(self, *, case_manifest: Mapping[str, Any] | None = None,
                 obligation_binding: Mapping[str, Any] | None = None,
                 runtime_binding: Mapping[str, Any] | None = None) -> None:
        self.case_manifest = dict(case_manifest) if case_manifest is not None else None
        self.obligation_binding = (
            dict(obligation_binding) if obligation_binding is not None else None
        )
        self.runtime_binding = (
            _check_runtime_binding(runtime_binding)
            if runtime_binding is not None else None
        )
        if self.case_manifest is not None:
            self._check_case_manifest(self.case_manifest)
            if self.runtime_binding is None:
                raise Room06LivT04EvaluatorError(
                    "case-bound evaluator requires frozen room06_runtime_binding"
                )

    @staticmethod
    def _check_case_manifest(case: Mapping[str, Any]) -> None:
        if case.get("task_id") != ANCHOR_ID or case.get("anchor_id") != ANCHOR_ID:
            raise Room06LivT04EvaluatorError("case manifest must bind liv-t-04")
        scene = _mapping(case.get("scene"), "case_manifest.scene")
        if scene.get("scene_id") not in SCENE_IDS:
            raise Room06LivT04EvaluatorError("case manifest scene is not room_06")
        if scene.get("horizon") != HORIZON_TICKS:
            raise Room06LivT04EvaluatorError("room_06 horizon must be 15000 ticks")
        entities = scene.get("entity_ids")
        if not isinstance(entities, list) or not ENTITY_IDS.issubset(entities):
            raise Room06LivT04EvaluatorError(
                "case manifest must bind book_batch_01 and heavy_object"
            )
        if scene.get("zone_ids") != []:
            raise Room06LivT04EvaluatorError(
                "liv-t-04 case manifest must have no registered zone resources"
            )
        evaluator = _mapping(case.get("evaluator"), "case_manifest.evaluator")
        if evaluator.get("evaluator_id") != EVALUATOR_ID:
            raise Room06LivT04EvaluatorError("case manifest evaluator id mismatch")
        if evaluator.get("evaluator_version") != EVALUATOR_VERSION:
            raise Room06LivT04EvaluatorError("case manifest evaluator version mismatch")

    @staticmethod
    def _check_job(job: Any) -> None:
        if getattr(job, "task_id", None) != ANCHOR_ID:
            raise Room06LivT04EvaluatorError("branch job task_id must be liv-t-04")
        if getattr(job, "scene_key", None) not in SCENE_IDS:
            raise Room06LivT04EvaluatorError("branch job scene_key must identify room_06")

    def collect_receipt_material(self, runtime: Any, job: Any) -> dict[str, Any]:
        """Return sealed input material after task-specific boundary checks."""

        self._check_job(job)
        payload = _payload(runtime)
        episode = dict(_mapping(payload["episode"], "episode"))
        job_system_id = _text(
            getattr(job, "system_id", None), "branch job system_id"
        )
        for key in ("condition_id", "repeat_id"):
            expected = _text(getattr(job, key, None), f"branch job {key}")
            actual = _text(episode.get(key), f"episode.{key}")
            if actual != expected:
                raise Room06LivT04EvaluatorError(
                    f"episode {key} disagrees with the branch job"
                )
        if episode.get("system_id", job_system_id) != job_system_id:
            raise Room06LivT04EvaluatorError(
                "episode system_id disagrees with the branch job"
            )
        episode["system_id"] = job_system_id
        if episode.get("evaluator_version", EVALUATOR_VERSION) != EVALUATOR_VERSION:
            raise Room06LivT04EvaluatorError("episode evaluator_version mismatch")
        episode["evaluator_version"] = EVALUATOR_VERSION
        payload_runtime_binding = _check_runtime_binding(payload["runtime_binding"])
        runtime_binding = self.runtime_binding or payload_runtime_binding
        if payload_runtime_binding != runtime_binding:
            raise Room06LivT04EvaluatorError(
                "runtime runtime_binding disagrees with the frozen plan binding"
            )
        streams = _check_streams(
            _mapping(payload["streams"], "streams"),
            transition_handoff_node_id=runtime_binding[
                "transition_handoff_node_id"
            ],
        )
        base_facts = _check_base_facts(_mapping(payload["base_facts"], "base_facts"))
        binding = payload.get("obligation_binding") or self.obligation_binding
        if not isinstance(binding, Mapping):
            raise Room06LivT04EvaluatorError(
                "frozen plan oracle_obligation_binding is required"
            )
        if binding.get("anchor_id") != ANCHOR_ID:
            raise Room06LivT04EvaluatorError("obligation binding must target liv-t-04")
        try:
            return assemble_oracle_receipt_material(
                episode=episode,
                streams=streams,
                base_facts=base_facts,
                anchor_id=ANCHOR_ID,
                obligation_binding=binding,
            )
        except ReceiptMaterialError as exc:
            raise Room06LivT04EvaluatorError(str(exc)) from exc


def build_diagnostic_runtime_fixture(
    *,
    late: bool = False,
    holders: int = 2,
    integrity_confirmed: bool = True,
) -> dict[str, Any]:
    """Return a deterministic CPU-only terminal payload for seam tests.

    This helper is intentionally *diagnostic-only*: it is not a simulator,
    does not read process status, and must never be used as a measured
    evaluator input.  The real task runtime is expected to replace this
    payload with its explicit episode/stream/base-fact ledgers.
    """

    if type(holders) is not int or holders < 0:
        raise ValueError("holders must be a non-negative integer")
    accepted_tick = HORIZON_TICKS + 1 if late else HORIZON_TICKS - 100
    return {
        "episode": {
            "status": "valid_terminal",
            "condition_id": "C0",
            "branch": "fact",
            "repeat_id": "r1",
            "checkpoint_id": "diagnostic-checkpoint",
            "evaluator_version": EVALUATOR_VERSION,
        },
        "streams": {
            "zone_intervals": [],
            "hold_intervals": [
                {
                    "object_id": "heavy_object",
                    "robot_id": f"carrier-{index}",
                    "start_tick": 10,
                    "end_tick": 20,
                }
                for index in range(holders)
            ],
            "milestones": [
                {"label": "relay_started", "tick": 1},
                {"label": "relay_complete", "tick": 3},
                {"label": "heavy_carry_complete", "tick": 20},
                {"label": "accepted", "tick": accepted_tick},
            ],
            "task_events": [
                {
                    "name": "transition_handoff_observed",
                    "subject": DIAGNOSTIC_RUNTIME_BINDING[
                        "transition_handoff_node_id"
                    ],
                    "tick": 2,
                },
                {
                    "name": "bilateral_support_established",
                    "subject": "heavy_object",
                    "tick": 10,
                },
            ],
            "identity_records": {},
            "integrity_confirmed": integrity_confirmed,
        },
        "base_facts": {
            "d1": {
                "validity": 1.0,
                "organization": 1.0,
                "infeasible": 0.0,
                "complete_plan": True,
            },
            "base_task_success": True,
            "d4_items": [],
            "d6": {"bits": 10.0, "time": 1.0},
        },
        "obligation_binding": DIAGNOSTIC_OBLIGATION_BINDING,
        "runtime_binding": DIAGNOSTIC_RUNTIME_BINDING,
    }


