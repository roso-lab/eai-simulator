"""Task-owned object placement for ``room_06 × liv-t-04``.

The room USD remains a static scene.  This module describes the two logical
objects generated by the case at runtime and resolves their initial pose from
the room semantic points.  It intentionally keeps the logical IDs stable so
the observer can bind ``held_object`` readback to the case ledger.
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any


TASK_ID = "liv-t-04"
BOOK_BATCH_ID = "book_batch_01"
HEAVY_OBJECT_ID = "heavy_object"
BOOK_PATH = "/World/envs/env_0/room06_task/book_batch_01"
HEAVY_PATH = "/World/envs/env_0/room06_task/heavy_object"


class Room06TaskObjectError(ValueError):
    """Raised when a task object cannot be placed from semantic evidence."""


def _point(points: Mapping[str, Any], label: str) -> tuple[float, float, float]:
    value = points.get(label)
    if not isinstance(value, (list, tuple)) or len(value) != 3:
        raise Room06TaskObjectError(f"semantic point is unavailable: {label}")
    try:
        result = tuple(float(item) for item in value)
    except (TypeError, ValueError) as exc:
        raise Room06TaskObjectError(f"semantic point is not numeric: {label}") from exc
    return result


def build_room06_task_object_plan(
    task_setup: Mapping[str, Any], semantic_points: Mapping[str, Any]
) -> dict[str, dict[str, Any]]:
    """Return a deterministic source/destination placement plan.

    ``semantic_points`` maps labels to world XYZ coordinates extracted from the
    accepted map.  The function does not guess missing labels and does not
    write to USD; the Isaac integration can use the returned plan to author
    task-owned rigid objects in a session layer.
    """

    if task_setup.get("task_id") != TASK_ID:
        raise Room06TaskObjectError("task setup must identify liv-t-04")
    rows = task_setup.get("objects")
    if not isinstance(rows, list):
        raise Room06TaskObjectError("task setup objects must be a list")
    by_id = {row.get("entity_id"): row.get("definition") for row in rows if isinstance(row, Mapping)}
    if set(by_id) != {BOOK_BATCH_ID, HEAVY_OBJECT_ID}:
        raise Room06TaskObjectError("task setup must contain the two liv-t-04 objects")

    books = by_id[BOOK_BATCH_ID]
    if not isinstance(books, Mapping) or books.get("source_semantic_point") != "floor1-bookshelf":
        raise Room06TaskObjectError("book batch source is not floor1-bookshelf")
    destinations = books.get("destination_semantic_points")
    if destinations != ["floor2-bookshelf-1", "floor2-bookshelf-2", "floor2-bookshelf-3"]:
        raise Room06TaskObjectError("book batch destinations are not the three upper shelves")
    book_source = _point(semantic_points, "floor1-bookshelf")
    book_destinations = [_point(semantic_points, label) for label in destinations]
    book_size = (0.45, 0.30, 0.24)

    heavy = by_id[HEAVY_OBJECT_ID]
    if not isinstance(heavy, Mapping) or heavy.get("minimum_holders") != 2:
        raise Room06TaskObjectError("heavy object must require two holders")
    heavy_source_label = heavy.get("source_semantic_point")
    heavy_destination_label = heavy.get("destination_semantic_point")
    heavy_source = _point(semantic_points, heavy_source_label)
    heavy_destination = _point(semantic_points, heavy_destination_label)
    size = heavy.get("size_xyz_m")
    if not isinstance(size, list) or len(size) != 3:
        raise Room06TaskObjectError("heavy object size must contain three values")
    heavy_size = tuple(float(item) for item in size)

    return {
        BOOK_BATCH_ID: {
            "entity_id": BOOK_BATCH_ID,
            "prim_path": BOOK_PATH,
            "kind": "logical_book_batch_proxy",
            "count": int(books["count"]),
            "source_semantic_point": "floor1-bookshelf",
            "source_position_m": list(book_source),
            "destination_semantic_points": list(destinations),
            "destination_positions_m": [list(item) for item in book_destinations],
            "size_xyz_m": list(book_size),
            "initial_center_m": [book_source[0], book_source[1], book_source[2] + book_size[2] / 2.0],
            "placement_policy": "task_generated_session_layer",
        },
        HEAVY_OBJECT_ID: {
            "entity_id": HEAVY_OBJECT_ID,
            "prim_path": HEAVY_PATH,
            "kind": "logical_load",
            "mass_kg": float(heavy["mass_kg"]),
            "minimum_holders": 2,
            "source_semantic_point": heavy_source_label,
            "source_position_m": list(heavy_source),
            "destination_semantic_point": heavy_destination_label,
            "destination_position_m": list(heavy_destination),
            "size_xyz_m": list(heavy_size),
            "initial_center_m": [heavy_source[0], heavy_source[1], heavy_source[2] + heavy_size[2] / 2.0],
            "placement_policy": "task_generated_session_layer",
        },
    }


def build_room06_task_object_configs(plan: Mapping[str, Mapping[str, Any]]) -> dict[str, Any]:
    """Build Isaac Lab ``RigidObjectCfg`` values from a validated plan.

    Imports Isaac Lab lazily so the deterministic placement plan remains
    usable by CPU preflight and artifact generators.
    """

    import isaaclab.sim as sim_utils
    from isaaclab.assets import RigidObjectCfg

    result: dict[str, Any] = {}
    for entity_id, row in plan.items():
        size = tuple(float(item) for item in row["size_xyz_m"])
        position = tuple(float(item) for item in row["initial_center_m"])
        result[entity_id] = RigidObjectCfg(
            prim_path=row["prim_path"],
            spawn=sim_utils.CuboidCfg(
                size=size,
                rigid_props=sim_utils.RigidBodyPropertiesCfg(),
                mass_props=sim_utils.MassPropertiesCfg(mass=float(row.get("mass_kg", 0.6))),
                collision_props=sim_utils.CollisionPropertiesCfg(contact_offset=0.001, rest_offset=0.0),
                visual_material=sim_utils.PreviewSurfaceCfg(
                    diffuse_color=(0.65, 0.35, 0.12) if entity_id == BOOK_BATCH_ID else (0.25, 0.28, 0.32)
                ),
            ),
            init_state=RigidObjectCfg.InitialStateCfg(pos=position),
        )
    return result


